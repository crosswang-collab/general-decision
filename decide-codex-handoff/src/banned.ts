/**
 * 護欄字表 — 第 7 節【絕對規則】1：罵行為，不罵人。
 * 禁止外貌、性別、族群、家庭、健康、性相關詞；禁止髒話。
 * 允許（不得列入本表）：猶豫、拖延、菜、屁股重、賴床。
 *
 * 這是護欄，不是保證（第 16 節）。單元測試會拿它掃 officers.ts 全部語料。
 */
export const BANNED = {
  髒話: ['幹', '靠北', '靠腰', '媽的', '他媽', '媽個', '王八', '混蛋', '渾蛋', '畜生', '去死', '屁啦', '雞掰', '三小'],
  人身: ['白痴', '智障', '腦殘', '低能', '蠢貨', '廢物', '垃圾', '沒用的東西'],
  外貌: ['胖子', '肥豬', '死胖', '醜', '矮子', '禿頭', '痘', '肥宅'],
  性別: ['娘炮', '娘娘腔', '婊', '賤', '死gay', '不男不女', '像個女人'],
  族群: ['外勞', '番仔', '支那', '阿六', '土人', '山地人'],
  家庭: ['你媽', '你爸', '你全家', '你老母', '沒家教', '你家人'],
  健康: ['殘廢', '瞎子', '聾子', '瘸', '神經病', '瘋子', '有病'],
  性: ['上床', '性器', '做愛', '打手槍'],
} as const

/** 攤平成一維字串陣列，供測試與 API 前置檢查使用。 */
export const BANNED_WORDS: string[] = Object.values(BANNED).flatMap((v) => [...v])

/** 回傳文字中命中的禁詞（空陣列 = 乾淨）。 */
export function findBanned(text: string): string[] {
  return BANNED_WORDS.filter((w) => text.includes(w))
}
